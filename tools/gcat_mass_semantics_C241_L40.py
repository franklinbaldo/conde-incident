"""Recheck actual GCAT bytes, rows, and column semantics for C241-L40.

GCAT is a mutable secondary catalog, not a historical spacecraft mass sheet.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "research/tle_custody/gcat_mass_semantics_C241-L40.json"


def field(row: str, header: str, key: str, next_key: str) -> str:
    return row[header.index(key):header.index(next_key)].strip()


def one_row(lines: list[str], prefix: str) -> str:
    matched = [x for x in lines if x.startswith(prefix + " ")]
    if len(matched) != 1:
        raise ValueError(f"Expected exactly one {prefix} row; got {len(matched)}")
    return matched[0]


def fingerprint(path: Path) -> tuple[int, str]:
    digest = hashlib.sha256()
    n = 0
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1024 * 1024), b""):
            n += len(chunk)
            digest.update(chunk)
    return n, digest.hexdigest()


def require(condition: bool, reason: str) -> None:
    """Runtime guard: not removed by Python's -O optimization."""
    if not condition:
        raise ValueError(reason)


def validate_claims(obj: dict) -> None:
    """Keep a pinned catalog transcription distinct from unsupported conclusions."""
    derived = obj["derived_checks"]
    rows = obj["rows"]
    conclusion = obj["conclusion"]
    require(set(derived) == {
        "s00527_mass_plus_agena_dry_mass_kg",
        "s00527_mass_plus_agena_launch_mass_kg",
        "catalog_total_mass_minus_sum_of_launch_masses_kg",
        "interpretation_of_30kg_difference",
        "three_norad_objects_mass_sum_kg",
    }, "unexpected field in inferred mass claims")
    source_mass = rows["S00527"]["mass_kg"]
    stage = rows["A00324"]
    require(derived["s00527_mass_plus_agena_dry_mass_kg"] == source_mass + stage["dry_mass_kg"],
            "dry-mass derived arithmetic changed")
    require(derived["s00527_mass_plus_agena_launch_mass_kg"] == source_mass + stage["mass_kg"],
            "launch-mass derived arithmetic changed")
    require(derived["catalog_total_mass_minus_sum_of_launch_masses_kg"] ==
            rows["S00527"]["total_mass_kg"] - derived["s00527_mass_plus_agena_launch_mass_kg"],
            "unexplained catalog mass difference changed")
    require(derived["interpretation_of_30kg_difference"] == "NOT_DEMONSTRATED",
            "unverified physical explanation promoted")
    require(derived["three_norad_objects_mass_sum_kg"] is None,
            "missing physical mass inventory invented")
    require(conclusion == {
        "totmass_1176_is_written_on_row": "S00527",
        "it_is_not_a_documented_sum_of_exclusive_527_528_529": True,
        "zero_for_debris_is_not_physical_mass_zero": True,
        "parent_launch_mass_balance_proven": False,
        "historical_mass_constraint_active": False,
        "instrumental_528_tracking_added": 0,
    }, "unsupported historical conclusion or unknown claim field")
    require(rows["1963-003"] == {
        "launch_type": "Thor Agena B",
        "orbmass_field_t": 0.0,
        "orbmass_supported_as_actual_measurement": False,
        "orbpay_field_t": 1.176,
        "orbpay_payload_kg": 1176,
        "orbpay_is_autogenerated_not_closed_mass_inventory": True,
    }, "OrbPay/OrbMass fields or historical provenance promoted")
    require(rows["S00528"]["mass_kg"] is None and rows["S00529"]["mass_kg"] is None
            and rows["S00528"]["dry_mass_kg"] is None
            and rows["S00529"]["dry_mass_kg"] is None,
            "placeholder debris masses promoted to measurements")


def replay(source_dir: Path, ledger: Path = MANIFEST) -> dict:
    obj = json.loads(ledger.read_text(encoding="utf-8"))
    require(obj["schema"] == "conde.gcat-mass-semantics-audit/v1", "GCAT assertion: obj['schema'] == 'conde.gcat-mass-semantics-audit/v1'")
    require(obj["source_kind"] == "DERIVED_SECONDARY_CATALOG_NOT_ENGINEERING_MASS_SHEET", "GCAT assertion: obj['source_kind'] == 'DERIVED_SECONDARY_CATALOG_NOT_ENGINEERING_MASS_")
    root = Path(source_dir)
    for name, meta in obj["files"].items():
        if fingerprint(root / name) != (meta["bytes"], meta["sha256"]):
            raise ValueError(f"GCAT source changed: {name}")
    for name, ids in (("satcat.html", ("S00527", "S00528", "S00529")),
                      ("auxcat.html", ("A00324",))):
        header = None
        found = {k: [] for k in ids}
        with (root / name).open(encoding="utf-8") as fh:
            for line in fh:
                if line.startswith("JCAT "):
                    header = line
                for ident in ids:
                    if line.startswith(ident + " "):
                        found[ident].append(line)
        require(header is not None, "GCAT assertion: header is not None")
        for ident in ids:
            row = one_row(found[ident], ident)
            expected = obj["rows"][ident]
            require(field(row, header, "Launch_Tag", "Piece") == expected["launch"], "GCAT assertion: field(row, header, 'Launch_Tag', 'Piece') == expected['launch']")
            require(field(row, header, "Piece", "Type") == expected["piece"], "GCAT assertion: field(row, header, 'Piece', 'Type') == expected['piece']")
            require(" ".join(field(row, header, "Type", "Name").split()) == " ".join(expected["type"].split()), "GCAT assertion: ' '.join(field(row, header, 'Type', 'Name').split()) == ' '.join(expec")
            for column, next_column, key in (("Mass", "DryMass", "mass_kg"),
                                              ("DryMass", "TotMass", "dry_mass_kg")):
                value = int(field(row, header, column, next_column))
                target = expected.get(key)
                if target is None:
                    target = expected[{"Mass": "mass_catalog_value_kg", "DryMass": "dry_mass_catalog_value_kg"}[column]]
                require(value == target, f"catalog mass column mismatch: {ident} {column}")
            total = int(field(row, header, "TotMass", "Length"))
            require(total == expected.get("total_mass_kg", expected.get("total_mass_catalog_value_kg")), "GCAT assertion: total == expected.get('total_mass_kg', expected.get('total_mass_catalo")
    header = None
    launch_rows = []
    with (root / "Thor.html").open(encoding="utf-8") as fh:
        for line in fh:
            if line.startswith("Launch_Tag "):
                header = line
            if line.startswith("1963-003 "):
                launch_rows.append(line)
    require(header is not None, "GCAT assertion: header is not None")
    row = one_row(launch_rows, "1963-003")
    require(field(row, header, "OrbMass", "OrbPay") == "0.000", "GCAT assertion: field(row, header, 'OrbMass', 'OrbPay') == '0.000'")
    require(field(row, header, "OrbPay", "Agency") == "1.176", "GCAT assertion: field(row, header, 'OrbPay', 'Agency') == '1.176'")
    payload_rows = []
    with (root / "psatcat.html").open(encoding="utf-8") as fh:
        for line in fh:
            if re.match(r"^S\d+\s+1963-003[A-Z]\s+", line):
                payload_rows.append(line)
    require(len(payload_rows) == 1 and payload_rows[0].startswith("S00527 "), "GCAT assertion: len(payload_rows) == 1 and payload_rows[0].startswith('S00527 ')")
    documentation = (root / "cols.html").read_text(encoding="utf-8")
    launch_docs = (root / "lcols.html").read_text(encoding="utf-8")
    for keyword in ("TotMass", "DryMass", "Mass of this GCAT object", "attached"):
        require(keyword in documentation, "GCAT assertion: keyword in documentation")
    for keyword in ("Orbital Payload", "autogenerated", "tonnes"):
        require(keyword in launch_docs, "GCAT assertion: keyword in launch_docs")
    require(obj["rows"]["S00528"]["mass_kg"] is None, "GCAT assertion: obj['rows']['S00528']['mass_kg'] is None")
    require(obj["rows"]["S00529"]["mass_kg"] is None, "GCAT assertion: obj['rows']['S00529']['mass_kg'] is None")
    require(obj["derived_checks"]["three_norad_objects_mass_sum_kg"] is None, "GCAT assertion: obj['derived_checks']['three_norad_objects_mass_sum_kg'] is None")
    require(obj["conclusion"]["historical_mass_constraint_active"] is False, "GCAT assertion: obj['conclusion']['historical_mass_constraint_active'] is False")
    require(obj["derived_checks"]["s00527_mass_plus_agena_dry_mass_kg"] == 306 + 870, "GCAT assertion: obj['derived_checks']['s00527_mass_plus_agena_dry_mass_kg'] == 306 + 8")
    require(obj["derived_checks"]["s00527_mass_plus_agena_launch_mass_kg"] == 306 + 900, "GCAT assertion: obj['derived_checks']['s00527_mass_plus_agena_launch_mass_kg'] == 306 ")
    validate_claims(obj)
    return obj


if __name__ == "__main__":
    import argparse
    parser = argparse.ArgumentParser()
    parser.add_argument("--source-dir", required=True, type=Path)
    args = parser.parse_args()
    result = replay(args.source_dir)
