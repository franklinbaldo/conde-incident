"""Source-locked mass catalogue -> physics-pending links (not historical bounds)."""
from __future__ import annotations

import copy
import hashlib
import json
from pathlib import Path
import sys
from tempfile import TemporaryDirectory
import unittest

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
from export_gcat_mass_semantic_bridge import (
    GCAT, PARTITION, BUDGET, OUT, DIGESTS, build, render,
)


class GcatMassBridgeTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.sources = [json.loads((ROOT / path).read_text())
                       for path in (GCAT, PARTITION, BUDGET)]

    def mutation(self, index, edit):
        data = copy.deepcopy(self.sources)
        edit(data[index])
        with self.assertRaises(ValueError):
            build(*data, DIGESTS)

    def test_export_is_reproducible_and_connects_unactivated_mass(self):
        self.assertEqual(OUT.read_bytes(), render())
        bridge = json.loads(render())
        self.assertEqual(bridge["source_occurrence"], "C241-L40")
        self.assertEqual(bridge["matrix_context"], "C61#1")
        self.assertEqual(len(bridge["dependency_graph"]), 10)
        self.assertEqual(len(bridge["catalogue_snapshots"]), 6)
        self.assertEqual(len(bridge["simulator_latent_parameters"]), 6)
        self.assertTrue(all(p["value"] is None and p["uncertainty"] is None
                            and p["activation"] is False
                            for p in bridge["simulator_latent_parameters"]))
        self.assertEqual(bridge["independent_instrumental_observations_added"], 0)
        self.assertFalse(bridge["activation"])
        self.assertFalse(bridge["conditional_equation_historical_activation"])
        self.assertEqual(bridge["physical_domain_effect"], "THETA_UNCHANGED")
        self.assertIn("NOT_COMPILED", bridge["lean_status"])

    def test_zeros_are_placeholders_not_measured_mass(self):
        d = json.loads(render())["documentary_observables"]
        self.assertEqual(d["s00528_mass_catalog_placeholder_kg"], 0)
        self.assertEqual(d["s00529_mass_catalog_placeholder_kg"], 0)
        self.assertIsNone(d["s00528_mass_observed_kg"])
        self.assertIsNone(d["s00529_mass_observed_kg"])
        self.mutation(0, lambda x: x["rows"]["S00528"].update(mass_kg=0))

    def test_mass_1176_not_three_body_sum(self):
        self.mutation(0, lambda x: x["derived_checks"].update(
            three_norad_objects_mass_sum_kg=1176))
        self.mutation(0, lambda x: x["conclusion"].update(
            it_is_not_a_documented_sum_of_exclusive_527_528_529=False))

    def test_changing_dry_mass_or_orbpay_breaks_source(self):
        self.mutation(0, lambda x: x["rows"]["A00324"].update(dry_mass_kg=900))
        self.mutation(0, lambda x: x["rows"]["1963-003"].update(
            orbpay_is_autogenerated_not_closed_mass_inventory=False))

    def test_invented_30kg_explanation_rejected(self):
        self.mutation(0, lambda x: x["derived_checks"].update(
            interpretation_of_30kg_difference="PROVEN_FUEL_BURN"))

    def test_false_independent_observation_rejected(self):
        self.mutation(0, lambda x: x["conclusion"].update(
            instrumental_528_tracking_added=1))
        self.mutation(0, lambda x: x.update(
            source_kind="PRIMARY_1963_ENGINEERING_MASS_SHEET"))

    def test_hypothetical_partition_must_remain_uncalibrated(self):
        self.mutation(1, lambda x: x["activation"].update(
            physical_constraint_active=True))
        self.mutation(1, lambda x: x["source"].update(
            object_coverage_confirmed=True))

    def test_conditional_equation_not_activated(self):
        self.mutation(2, lambda x: x["conditional_budget"].update(
            physically_calibrated_historical_constraint=True))
        self.mutation(2, lambda x: x["conditional_derived_bounds"].update(
            numeric_historical_domain_reduction=True))
        self.mutation(2, lambda x: x["source"].update(
            observed_individual_mass_of_528_kg=1))

    def test_manifest_or_metadata_tamper_rejected(self):
        self.mutation(0, lambda x: x["files"]["satcat.html"].update(
            sha256="0" * 64))
        self.mutation(0, lambda x: x["files"].pop("cols.html"))
        with self.assertRaises(ValueError):
            build(*self.sources, {**DIGESTS, GCAT: "0" * 64})

    def test_render_checks_source_bytes_not_only_structure(self):
        with TemporaryDirectory() as temp:
            d = Path(temp)
            for path in DIGESTS:
                dest = d / path
                dest.parent.mkdir(parents=True, exist_ok=True)
                dest.write_bytes((ROOT / path).read_bytes())
            self.assertEqual(render(d), render())
            source = d / GCAT
            source.write_bytes(source.read_bytes() + b" ")
            with self.assertRaises(ValueError):
                render(d)

    def test_pinned_digest_matches_physical_source(self):
        for path, expected in DIGESTS.items():
            self.assertEqual(hashlib.sha256((ROOT / path).read_bytes()).hexdigest(),
                             expected)


if __name__ == "__main__":
    unittest.main()
