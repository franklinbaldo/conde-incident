"""Distinguish GCAT's catalog fields from historical closed mass inventory."""
import json
import sys
from pathlib import Path
import tempfile
import unittest
from unittest.mock import patch
import subprocess

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from tools.gcat_mass_semantics_C241_L40 import MANIFEST, field, one_row, replay


class TestC241L40(unittest.TestCase):
    def test_catalog_is_not_a_mass_measurement_of_three_debris(self):
        m = json.loads(MANIFEST.read_text())
        self.assertEqual(m["rows"]["S00527"]["total_mass_kg"], 1176)
        self.assertEqual(m["rows"]["S00527"]["mass_kg"], 306)
        self.assertIsNone(m["rows"]["S00528"]["mass_kg"])
        self.assertIsNone(m["rows"]["S00529"]["mass_kg"])
        self.assertIsNone(m["derived_checks"]["three_norad_objects_mass_sum_kg"])
        self.assertFalse(m["conclusion"]["historical_mass_constraint_active"])

    def test_306_plus_870_is_1176_but_306_plus_900_is_1206(self):
        m = json.loads(MANIFEST.read_text())["rows"]
        self.assertEqual(m["S00527"]["mass_kg"] + m["A00324"]["dry_mass_kg"], 1176)
        self.assertEqual(m["S00527"]["mass_kg"] + m["A00324"]["mass_kg"], 1206)

    def test_exact_column_parser(self):
        self.assertEqual(field("a  0123  zz", "a  Mass  Next", "Mass", "Next"), "0123")
        self.assertEqual(one_row(["X  abc", "Y def"], "X"), "X  abc")
        with self.assertRaises(ValueError):
            one_row(["X abc", "X def"], "X")

    def test_manifest_source_hashes_are_complete(self):
        m = json.loads(MANIFEST.read_text())
        self.assertEqual(set(m["files"]), {
            "satcat.html", "auxcat.html", "psatcat.html",
            "Thor.html", "cols.html", "lcols.html"
        })
        for s in m["files"].values():
            self.assertEqual(len(s["sha256"]), 64)
            self.assertGreater(s["bytes"], 10_000)
            self.assertTrue(s["url"].startswith("https://planet4589.org/"))

    @staticmethod
    def _sample_sources(root: Path):
        """Tiny transport fixtures; fingerprints deliberately mocked, not source evidence."""
        columns = [('JCAT', 10), ('Launch_Tag', 16), ('Piece', 17),
                   ('Type', 10), ('Name', 28), ('Mass', 9),
                   ('DryMass', 11), ('TotMass', 11), ('Length', 10)]
        def line(values):
            return ''.join(str(values.get(key, '')).ljust(width) for key, width in columns) + "\n"
        header = line({key: key for key, _ in columns})
        rows = {
            'S00527': dict(JCAT='S00527', Launch_Tag='1963-003', Piece='1963-003A',
                           Type='P A', Mass='306', DryMass='306', TotMass='1176'),
            'S00528': dict(JCAT='S00528', Launch_Tag='1963-003', Piece='1963-003B',
                           Type='C X', Mass='0', DryMass='0', TotMass='0'),
            'S00529': dict(JCAT='S00529', Launch_Tag='1963-003', Piece='1963-003C',
                           Type='C X', Mass='0', DryMass='0', TotMass='0'),
            'A00324': dict(JCAT='A00324', Launch_Tag='1963-003', Piece='1963-003A',
                           Type='R2', Name='Agena B 2313', Mass='900', DryMass='870', TotMass='0'),
        }
        (root / 'satcat.html').write_text(header + ''.join(line(rows[x]) for x in ('S00527','S00528','S00529')))
        (root / 'auxcat.html').write_text(header + line(rows['A00324']))
        launch_columns = [('Launch_Tag', 16), ('OrbMass', 12), ('OrbPay', 12), ('Agency', 12)]
        fmt = lambda d: ''.join(str(d.get(k, '')).ljust(w) for k,w in launch_columns) + "\n"
        (root / 'Thor.html').write_text(fmt({k:k for k,w in launch_columns}) +
                        fmt(dict(Launch_Tag='1963-003', OrbMass='0.000', OrbPay='1.176')))
        (root / 'psatcat.html').write_text('S00527 1963-003A SAMPLE\n')
        (root / 'cols.html').write_text('TotMass DryMass Mass of this GCAT object attached')
        (root / 'lcols.html').write_text('Orbital Payload autogenerated tonnes')

    def test_mutated_semantic_claims_rejected_even_when_bytes_unchanged(self):
        baseline = json.loads(MANIFEST.read_text())
        with tempfile.TemporaryDirectory() as d:
            root = Path(d)
            self._sample_sources(root)
            def fingerprint_stub(path):
                m = baseline['files'][path.name]
                return m['bytes'], m['sha256']
            with patch('tools.gcat_mass_semantics_C241_L40.fingerprint', side_effect=fingerprint_stub):
                original = replay(root)
                self.assertFalse(original['conclusion']['historical_mass_constraint_active'])
                mutations = (
                    ('conclusion', 'parent_launch_mass_balance_proven', True),
                    ('conclusion', 'instrumental_528_tracking_added', 1),
                    ('conclusion', 'it_is_not_a_documented_sum_of_exclusive_527_528_529', False),
                    ('conclusion', 'zero_for_debris_is_not_physical_mass_zero', False),
                    ('derived_checks', 'interpretation_of_30kg_difference', 'PROVEN_FUEL_LOSS'),
                    ('derived_checks', 'catalog_total_mass_minus_sum_of_launch_masses_kg', 0),
                )
                for group, key, value in mutations:
                    altered = json.loads(json.dumps(baseline))
                    altered[group][key] = value
                    ledger = root / 'mutant-ledger.json'
                    ledger.write_text(json.dumps(altered))
                    with self.subTest(key=key), self.assertRaises(ValueError):
                        replay(root, ledger)
                for key, value in (('orbpay_payload_kg', 528),
                                   ('orbmass_supported_as_actual_measurement', True)):
                    altered = json.loads(json.dumps(baseline))
                    altered['rows']['1963-003'][key] = value
                    ledger = root / 'mutant-ledger.json'
                    ledger.write_text(json.dumps(altered))
                    with self.subTest(key=key), self.assertRaises(ValueError):
                        replay(root, ledger)

    def test_optimized_interpreter_must_enforce_semantic_guards(self):
        with tempfile.TemporaryDirectory() as d:
            root = Path(d)
            self._sample_sources(root)
            altered = json.loads(MANIFEST.read_text())
            altered['conclusion']['historical_mass_constraint_active'] = True
            manifest = root / 'mutant-ledger.json'
            manifest.write_text(json.dumps(altered))
            code = (
                'import json,sys; from pathlib import Path; '
                'import tools.gcat_mass_semantics_C241_L40 as m; '
                'b=json.loads(m.MANIFEST.read_text()); '
                'm.fingerprint=lambda p:(b["files"][p.name]["bytes"],b["files"][p.name]["sha256"]); '
                'm.replay(Path(sys.argv[1]),Path(sys.argv[2]))'
            )
            process = subprocess.run([sys.executable, '-O', '-c', code, str(root), str(manifest)],
                         cwd=ROOT, capture_output=True, text=True, check=False)
            self.assertNotEqual(process.returncode, 0, 'python -O must not disable scientific validation')

    def test_mutation_of_hash_does_not_pass_replay(self):
        m = json.loads(MANIFEST.read_text())
        m["files"]["satcat.html"]["sha256"] = "0" * 64
        with tempfile.TemporaryDirectory() as d:
            tmp = Path(d)
            path = tmp / "mutant.json"
            path.write_text(json.dumps(m))
            (tmp / "satcat.html").write_text("broken")
            with self.assertRaises(ValueError):
                replay(tmp, path)


if __name__ == "__main__":
    unittest.main()
