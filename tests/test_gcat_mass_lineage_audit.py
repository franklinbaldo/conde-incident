"""Adversarial review of GCAT object/stage mass semantics and double-counting."""
import copy
import json
import unittest
from pathlib import Path
from tools.gcat_mass_lineage_audit import validate

ROOT=Path(__file__).resolve().parents[1]
DATA=json.loads((ROOT/"research/constraints/C241_L39_stage_payload_mass_semantics_20261113.json").read_text())
MATRIX=(ROOT/"research/evidence_matrix_C001-C238_2026-11-11.md").read_text()
AUX=json.loads((ROOT/"research/tle_custody/gcat_identity_527_529_C241-L13.json").read_text())
CAT=json.loads((ROOT/"research/tle_custody/gcat_full_catalog_lineage_C241-L14.json").read_text())

class GcatMassLineage(unittest.TestCase):
    def invalid(self,slot,change):
        items=[copy.deepcopy(DATA),MATRIX,copy.deepcopy(AUX),copy.deepcopy(CAT)]
        if slot==1:items[1]=change(items[1])
        else:change(items[slot])
        with self.assertRaises((ValueError,KeyError,TypeError,StopIteration)):
            validate(*items)

    def test_source_locked_two_mass_bases(self):
        r=validate(DATA,MATRIX,AUX,CAT)
        self.assertEqual(r["mass_sum_wet_kg"],1206)
        self.assertEqual(r["mass_sum_dry_kg"],1176)
        self.assertEqual(r["unresolved_basis_difference_kg"],30)
        self.assertFalse(r["m527_equals_payload_306_proven"])
        self.assertFalse(r["historical_mass_posterior_available"])

    def test_wrong_payload(self):
        self.invalid(0,lambda x:x["sources"]["payload"].update(Mass_kg=376))

    def test_wrong_stage_wet(self):
        self.invalid(0,lambda x:x["sources"]["stage"].update(Mass_kg=870))

    def test_wrong_stage_dry(self):
        self.invalid(0,lambda x:x["sources"]["stage"].update(DryMass_kg=900))

    def test_wrong_catalog_total(self):
        self.invalid(0,lambda x:x["sources"]["payload"].update(TotMass_associated_kg=1206))

    def test_payload_dry_mass_is_component_306_not_composite(self):
        self.invalid(0,lambda x:x["sources"]["payload"].update(DryMass_kg=305))

    def test_catalog_OrbPay_is_not_total_mass_sensed_in_orbit(self):
        self.invalid(0,lambda x:x["findings"].update(
            launch_orbpay_autogenerated_not_closed_orbit_inventory=False))

    def test_catalog_OrbMass_zero_not_a_real_zero(self):
        self.invalid(0,lambda x:x["sources"]["detailed_gcataudit"]["launch_row"].update(
            OrbMass_field_is_physical_measurement=True))

    def test_mass_semantics_link_is_to_C241_L40(self):
        self.invalid(0,lambda x:x["sources"]["detailed_gcataudit"].update(
            citation_id="C241-L99"))

    def test_no_false_propellant_history(self):
        self.invalid(0,lambda x:x["findings"].update(stage_consumed_30_kg_is_observed=True))

    def test_m527_not_306_unless_stage_detached(self):
        self.invalid(0,lambda x:x["physical_model"].update(m527_equals_306_directly=True))

    def test_catalog_difference_not_extra_mass(self):
        self.invalid(0,lambda x:x["physical_model"].update(
            catalog_30_kg_difference_is_not_additional_mass=False))

    def test_no_empirical_small_X_prior(self):
        self.invalid(0,lambda x:x["physical_model"].update(X_small_prior_empirical=True))

    def test_historical_model_weights_absent(self):
        self.invalid(0,lambda x:x["mcmc_bridge"].update(no_evidence_for_model_weights=False))

    def test_stage_ancestor_gcat_crosswalk(self):
        self.invalid(3,lambda x:x["catalogue_labels"]["00528"].update(reported_parent="A00324"))

    def test_stage_catalog_identity(self):
        self.invalid(2,lambda x:next(k for k in x["sources"] if k["id"]=="GCAT_AUX").update(
            record_key="A00000"))

    def test_original_1963_document_not_recovered(self):
        self.invalid(0,lambda x:x["findings"].update(historical_masses_identified=True))

    def test_scenario_basis_not_promoted(self):
        self.invalid(0,lambda x:x["accounting_scenarios"][0].update(validity="PRIMARY_VERIFIED"))

    def test_1176_is_not_a_direct_528_mass(self):
        self.invalid(0,lambda x:x["findings"].update(unknown_mass_528_kg=1176))

    def test_legacy_source_is_locked(self):
        self.invalid(1,lambda x:x.replace("~1176 kg","~1206 kg"))

if __name__=="__main__":
    unittest.main()
