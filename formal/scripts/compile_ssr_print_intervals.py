#!/usr/bin/env python3
"""C241-P8: quantify NASA April/October publication deltas under *assumed* rounding.

The reports' publication dates are NOT tracking epochs. The bounds say what
one-decimal printed nodal periods imply IF rounded to nearest 0.1 min;
not measured instrument sigma, not orbital change per unit time.
"""
from __future__ import annotations

import argparse
from decimal import Decimal
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from tools.tle_nasa_ssr_apr_oct_audit import validate  # noqa: E402

APR = ROOT / 'research/tle_custody/nasa_ssr_apr_oct_1963_C241-L16.json'
OCT = ROOT / 'research/tle_custody/nasa_ssr_1963_oct15_C241-L12.json'
LEAN = ROOT / 'formal/Conde1963/SsrPrintIntervals.lean'
REPORT = ROOT / 'research/constraints/C241-P8_ssr_print_intervals.json'


def _centiminutes(value: str) -> int:
    period = Decimal(value)
    if (period * 10) != (period * 10).to_integral_value():
        raise ValueError('period is not printed at one decimal')
    return int(period * 100)


def intervals(april: dict, october: dict) -> dict:
    rows = validate(april, october)  # fail closed on documentary identity and lineage
    objects = []
    for row in rows:
        before = _centiminutes(row['april_period_min'])
        after = _centiminutes(row['october_period_min'])
        # ±0.05 minute around a value printed to 0.1 minute.
        diff_lo, diff_hi = before - after - 10, before - after + 10
        if diff_lo > diff_hi:
            raise AssertionError('negative interval')
        objects.append({
            'designator': row['designator'],
            'april_printed_centiminutes': before,
            'october_printed_centiminutes': after,
            'conditional_april_minus_october_centiminutes': [diff_lo, diff_hi],
            'printed_period_change_robust_to_nearest_tenth_rounding': diff_lo > 0 or diff_hi < 0,
            'printed_apogee_delta_oct_minus_apr_km': row['published_delta_apogee_km'],
            'printed_perigee_delta_oct_minus_apr_km': row['published_delta_perigee_km'],
            'observed_epoch': None, 'instrumental_uncertainty': None,
            'measured_decay_rate': None,
        })
    return {
        'id': 'C241-P8', 'schema': 'conde.ssr-printed-period-intervals/v1',
        'sources': [
            {'id': april['id'], 'publication': april['april']['publication'],
             'url': april['april']['url'], 'sha256': april['april']['sha256'],
             'printed_page': april['april']['printed_page']},
            {'id': october['record_id'], 'publication': october['source']['publication_date'],
             'url': october['source']['pdf_url'], 'sha256': october['source']['sha256'],
             'printed_page': october['source']['page_printed']},
        ],
        'precision': 'ONE_DECIMAL_MINUTE_PRINTED; NEAREST_ROUNDING_HYPOTHESIS',
        'unit': '0.01 minute',
        'interpretation': 'BOUNDED_CROSS_EDITION_PRINTED_VALUES_NOT_ORBITAL_EPOCHS',
        'upstream_family': 'NASA_GODDARD_COMPILED_REPORT_NOT_INDEPENDENT_SENSORS',
        'physical_domain_change': 'NONE_NO_HISTORICAL_EPOCH_OR_INSTRUMENT_SIGMA',
        'objects': objects,
    }


def render_lean(report: dict) -> str:
    # These are quantified, rounding-bounded comparisons, not equality proofs
    # for a curated JSON row, nor a physical orbit propagation theorem.
    lines = [
        'import Lean', '', 'namespace Conde1963.SsrPrintIntervals', '',
        '/-! Generated by compile_ssr_print_intervals.py. Source: C241-L16 and C241-L12.',
        'Assumption: each printed period is nearest-rounding to 0.1 minute.',
        'Int values model hundredths of a minute (a discrete centiminute grid).',
        'Quantified results constrain only differences in catalogued table values,',
        'NOT true 1963 orbital periods, source independence, or sensor precision. -/', '',
    ]
    for row in report['objects']:
        name = row['designator'][-1].lower()
        apr, octo = row['april_printed_centiminutes'], row['october_printed_centiminutes']
        dlo, dhi = row['conditional_april_minus_october_centiminutes']
        lines += [
            f'/-- Printed 1963-003{name.upper()}: April vs October, conditional rounding in 0.01 min. -/',
            f'theorem period_{name}_documentary_difference (apr oct : Int)',
            f'    (hAprLo : {apr-5} ≤ apr) (hAprHi : apr ≤ {apr+5})',
            f'    (hOctLo : {octo-5} ≤ oct) (hOctHi : oct ≤ {octo+5}) :',
            f'    {dlo} ≤ apr - oct ∧ apr - oct ≤ {dhi} := by',
            '  omega', '',
        ]
    lines += ['end Conde1963.SsrPrintIntervals', '']
    return '\n'.join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    report = intervals(json.loads(APR.read_text()), json.loads(OCT.read_text()))
    expected = json.dumps(report, ensure_ascii=False, indent=2, sort_keys=True) + '\n'
    lean = render_lean(report)
    if args.check:
        if REPORT.read_text() != expected or LEAN.read_text() != lean:
            raise SystemExit('C241-P8 source export drift: run generator and review')
        print('C241-P8 checked: 3 NASA table lineages and quantified rounding bounds')
    else:
        REPORT.write_text(expected)
        LEAN.write_text(lean)
        print('C241-P8 generated')


if __name__ == '__main__':
    main()
