#!/usr/bin/env python3
"""Compile real 1964 ON20 custody and missing 1963 layout bridge to Lean data."""
from __future__ import annotations
import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools"))
import export_nmc_on20_layout_link as link  # noqa: E402
TARGET = ROOT / "formal/Conde1963/NmcLayout.lean"


def assemble(data: dict) -> str:
    if (data != link.build() or data["active_physical_constraint"] is not False
        or data["validated_1963_layout_reference"] is not None
        or data["decoded_station_day_matches"] is not None):
        raise ValueError("ON20 conditionality differs from audited documentary feeds")
    s = lambda v: json.dumps(v, ensure_ascii=False)
    return '''import Conde1963.NmcCandidate

/-!
1964 NMC Office Note 20 archived PDF linked to 1963 Y20175 *candidate*.
The 1963 record layout remains unverified. No numeric wind or orbit bound.
Generated by formal/scripts/compile_nmc_layout_link.py.
-/

namespace Conde1963

structure HistoricalNmcLayoutCandidate where
  manuscriptSource : String
  originalYear : Nat
  archiveDateUtc : String
  facsimileSha256 : String
  tapeSource : String
  tapeSha256 : String
  layout1963Source : Option String
  decodedStationDays : Option Nat
  deriving Repr

def pendingHistoricalNmcLayout : HistoricalNmcLayoutCandidate := {
  manuscriptSource := ''' + s(data["lineage"][0]["to"]) + '''
  originalYear := ''' + str(data["manual_publication_year"]) + '''
  archiveDateUtc := ''' + s(data["wayback_capture_utc"]) + '''
  facsimileSha256 := ''' + s(data["wayback_pdf_sha256"]) + '''
  tapeSource := pendingNmcSourceId
  tapeSha256 := pendingNmcArchiveSha256
  layout1963Source := none
  decodedStationDays := none
}

end Conde1963
'''


def main() -> None:
    p = argparse.ArgumentParser()
    g = p.add_mutually_exclusive_group(required=True)
    g.add_argument("--check", action="store_true")
    g.add_argument("--write", action="store_true")
    args = p.parse_args()
    data = link.build()
    if link.encode(data) != (ROOT / link.OUTPUT).read_bytes():
        raise SystemExit("stale ON20 link; export before compiling")
    lean = assemble(data)
    if args.check:
        if TARGET.read_text(encoding="utf-8") != lean:
            raise SystemExit("stale generated NmcLayout.lean")
    else:
        TARGET.write_text(lean, encoding="utf-8")
    print("NMC_LAYOUT_LEAN", len(lean.encode()), "bytes")


if __name__ == "__main__":
    main()
