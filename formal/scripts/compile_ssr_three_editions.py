"""C241-P9: connect April/August/October 1963 NASA printings to Lean.

This is conditional quantization of documentary fields, not an orbital
dynamics constraint. Intermediate August rounding error is *shared*
between adjacent differences, rather than two independent observations.
"""
from __future__ import annotations

import argparse
from decimal import Decimal
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from tools.tle_nasa_ssr_aug15_audit import validate as validate_three  # noqa: E402
from formal.scripts.compile_ssr_print_intervals import intervals as validate_pair  # noqa: E402

APR = ROOT / "research/tle_custody/nasa_ssr_apr_oct_1963_C241-L16.json"
AUG = ROOT / "research/tle_custody/nasa_ssr_aug15_1963_C241-L17.json"
OCT = ROOT / "research/tle_custody/nasa_ssr_1963_oct15_C241-L12.json"
REPORT = ROOT / "research/constraints/C241-P9_ssr_three_edition_intervals.json"
LEAN = ROOT / "formal/Conde1963/SsrThreeEditions.lean"


def cents(x: str) -> int:
    value = Decimal(x)
    if value * 10 != (value * 10).to_integral_value():
        raise ValueError("source must print to exactly one decimal minute")
    return int(value * 100)


def bounds(a: int, b: int) -> list[int]:
    return [a - b - 10, a - b + 10]


def compile_report(april: dict, august: dict, october: dict) -> dict:
    rows = validate_three(august, april, october)
    prior = validate_pair(april, october)
    objects = []
    for row, previous in zip(rows, prior["objects"]):
        a, u, o = [cents(x) for x in row["printed_period_min"]]
        if [a, o] != [previous["april_printed_centiminutes"],
                      previous["october_printed_centiminutes"]]:
            raise ValueError("independent April/October audit disagrees")
        objects.append({
            "designator": row["designator"],
            "printed_period_centiminutes": [a, u, o],
            "apr_minus_aug": bounds(a, u),
            "aug_minus_oct": bounds(u, o),
            "apr_minus_oct_shared_aug_eliminated": bounds(a, o),
            "robust_positive_adjacent_differences": [
                bounds(a, u)[0] > 0, bounds(u, o)[0] > 0
            ],
            "instrumental_epochs_utc": None,
            "measurement_uncertainty": None,
            "physical_decay_rate": None,
        })
    # Documentary rank order is a robust property of printed fields under
    # the ASSUMED rounding. It does not rank physical drag/decay rates.
    a, b, c = objects
    ranking = {
        "apr_aug_b_strictly_greater_than_c":
            b["apr_minus_aug"][0] > c["apr_minus_aug"][1],
        "aug_oct_b_strictly_greater_than_c":
            b["aug_minus_oct"][0] > c["aug_minus_oct"][1],
        "apr_aug_c_strictly_greater_than_a":
            c["apr_minus_aug"][0] > a["apr_minus_aug"][1],
        "aug_oct_c_strictly_greater_than_a":
            c["aug_minus_oct"][0] > a["aug_minus_oct"][1],
    }
    if not all(ranking.values()):
        raise ValueError("expected robust printed differences not verified")
    return {
        "id": "C241-P9",
        "schema": "conde.ssr-three-edition-printed-bounds/v1",
        "source_ids": ["C241-L16", "C241-L17", "C241-L12"],
        "document_sha256": [
            april["april"]["sha256"],
            august["source"]["sha256"],
            october["source"]["sha256"],
        ],
        "source_publication_dates": [
            april["april"]["publication"],
            august["source"]["publication"],
            october["source"]["publication_date"],
        ],
        "source_family": "NASA_GODDARD_COMPILED_REPORT_NOT_INDEPENDENT_SENSORS",
        "hypothesis": "NEAREST_TENTH_MINUTE_ROUNDING_OF_PRINTED_VALUES",
        "uncertainty": "Each actual printed value in center ±0.05 min; not sensor sigma",
        "arithmetic": "April-August + August-October = April-October; shared August uncertainty cancels",
        "quantization_unit": "0.01 minute",
        "interpretation": "DOCUMENTARY_CROSS_EDITION_RANK_ONLY_NOT_PHYSICAL_CHANGE",
        "link_status": "CONNECTED_PENDING_CALIBRATION",
        "activation_blockers": [
            "observation_epochs", "instrumental_error", "common_element_definition",
            "validated_dynamical_forward_operator",
        ],
        "physical_domain_change": "NONE",
        "objects": objects,
        "conditional_robust_printed_rank": ranking,
    }


def render_lean(report: dict) -> str:
    lines = [
        "import Lean",
        "",
        "namespace Conde1963.SsrThreeEditions",
        "",
        "/-! Generated by compile_ssr_three_editions.py from C241-L16/L17/L12.",
        "Each value is a hundredth of a minute, conditionally within five",
        "centiminutes of its independently printed one-decimal entry.",
        "A shared August value cancels in the April-to-October total.",
        "These are documentary comparisons, NOT orbital epochs,",
        "tracking errors, physical decay rates or independent sensors. -/",
        "",
    ]
    for obj in report["objects"]:
        tag = obj["designator"][-1].lower()
        a, u, o = obj["printed_period_centiminutes"]
        p, q = obj["apr_minus_aug"], obj["aug_minus_oct"]
        whole = obj["apr_minus_oct_shared_aug_eliminated"]
        lines += [
            f"/-- 1963-003{tag.upper()}: three publications, rounding hypothesis only. -/",
            f"theorem period_{tag}_three_printings (apr aug oct : Int)",
            f"    (ha0 : {a-5} ≤ apr) (ha1 : apr ≤ {a+5})",
            f"    (hu0 : {u-5} ≤ aug) (hu1 : aug ≤ {u+5})",
            f"    (ho0 : {o-5} ≤ oct) (ho1 : oct ≤ {o+5}) :",
            f"    ({p[0]} ≤ apr - aug ∧ apr - aug ≤ {p[1]}) ∧",
            f"    ({q[0]} ≤ aug - oct ∧ aug - oct ≤ {q[1]}) ∧",
            f"    ({whole[0]} ≤ apr - oct ∧ apr - oct ≤ {whole[1]}) ∧",
            "    ((apr - aug) + (aug - oct) = apr - oct) := by",
            "  omega", "",
        ]
    a, b, c = report["objects"]
    # Conditional ranking across *separate NASA table rows*.
    for step, i, j in (("apr_aug", 0, 1), ("aug_oct", 1, 2)):
        v = ("apr", "aug", "oct")
        names = ["b", "c", "a"]
        for higher, lower in (("b", "c"), ("c", "a")):
            first = {"a": a, "b": b, "c": c}[higher]["printed_period_centiminutes"]
            second = {"a": a, "b": b, "c": c}[lower]["printed_period_centiminutes"]
            x, y, x2, y2 = first[i], first[j], second[i], second[j]
            lines += [
                f"/-- {step}: printed 3{higher.upper()} interval lies strictly above 3{lower.upper()}. -/",
                f"theorem printed_{step}_{higher}_gt_{lower} (x0 x1 y0 y1 : Int)",
                f"    (hx0lo : {x-5} ≤ x0) (hx0hi : x0 ≤ {x+5})",
                f"    (hx1lo : {y-5} ≤ x1) (hx1hi : x1 ≤ {y+5})",
                f"    (hy0lo : {x2-5} ≤ y0) (hy0hi : y0 ≤ {x2+5})",
                f"    (hy1lo : {y2-5} ≤ y1) (hy1hi : y1 ≤ {y2+5}) :",
                "    y0 - y1 < x0 - x1 := by",
                "  omega", "",
            ]
    lines += ["end Conde1963.SsrThreeEditions", ""]
    return "\n".join(lines)


def main() -> None:
    cli = argparse.ArgumentParser()
    cli.add_argument("--check", action="store_true")
    args = cli.parse_args()
    report = compile_report(*(json.loads(p.read_text()) for p in (APR, AUG, OCT)))
    rendered = json.dumps(report, indent=2, sort_keys=True, ensure_ascii=False) + "\n"
    lean = render_lean(report)
    if args.check:
        if REPORT.read_text() != rendered or LEAN.read_text() != lean:
            raise SystemExit("C241-P9 generated artifacts drift; regenerate and inspect")
        print("C241-P9: 3 NASA editions, shared error cancellation and printed ranks checked")
    else:
        REPORT.write_text(rendered)
        LEAN.write_text(lean)
        print("C241-P9 artifacts generated")


if __name__ == "__main__":
    main()
