#!/usr/bin/env python3
"""Generate a source-locked Lean check of the 1963 P-17 A.1-minus-WWV step.

Nanoseconds are an exact fixed-point encoding of the printed decimal
formula at integer MJD. This is NOT a conversion to UTC, nor a 528 sensor.
"""
from __future__ import annotations

import argparse
from decimal import Decimal
import json
from pathlib import Path
from string import Template

from tools import tle_sao_p17_wwv_step_c241_l61 as p17

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "formal/Conde1963/SaoP17ClockStep.lean"
TEMPLATE = Template("""import Lean

/-!
Source-locked C241-L61, Smithsonian Astrophysical Observatory P-17,
NASA NTRS 19680020675, printed page 3.
Exact nanoseconds at integer Modified Julian Days in the published
WWV(emitted) -> preliminary smoothed A.1 convention. **NOT UTC**.
Ledger: research/tle_custody/sao_p17_nov_clock_C241-L61.json
Generated by formal/scripts/compile_sao_p17_clock_step.py.
The lower and upper branch formulas are both evaluated at the same
boundary to test whether a single affine clock correction could fit.
Neither a film timestamp nor a NORAD 528 measurement is represented.
-/
namespace Conde1963.SaoP17ClockStep

def lowerExtension (mjd : Int) : Int :=
  $lower + $rate * (mjd - $origin)

def upperExtension (mjd : Int) : Int :=
  $upper + $rate * (mjd - $origin)

def publishedCorrection (mjd : Int) : Int :=
  if mjd < $cut then lowerExtension mjd else upperExtension mjd

/-- The two documented affine extensions disagree by $jump nanoseconds
at every identical MJD, independent of how many days have elapsed. -/
theorem branch_difference (mjd : Int) :
    upperExtension mjd - lowerExtension mjd = $jump := by
  unfold upperExtension lowerExtension
  omega

/-- The left and right formulas cannot both be produced by one
single-valued continuous affine correction at the November boundary. -/
theorem no_single_affine_boundary_value (value : Int) :
    ¬ (value = lowerExtension $cut ∧ value = upperExtension $cut) := by
  intro h
  have hgap := branch_difference $cut
  omega

/-- Published November 8, 1963 integer-MJD example, in nanoseconds.
This is A.1-minus-WWV, not an observed timestamp or UTC offset. -/
theorem november_8_published_convention :
    publishedCorrection 38341 = $nov8 := by
  decide

/-- The second branch is selected at and after the printed cutoff. -/
theorem upper_branch_after_boundary (mjd : Int) (h : $cut ≤ mjd) :
    publishedCorrection mjd = upperExtension mjd := by
  simp [publishedCorrection, show ¬ mjd < $cut by omega]

/-- Away from the jump, one MJD integer day adds the printed slope. -/
theorem second_branch_daily_increment (mjd : Int) :
    upperExtension (mjd + 1) - upperExtension mjd = $rate := by
  unfold upperExtension
  omega

end Conde1963.SaoP17ClockStep
""")


def to_ns(seconds: str) -> int:
    ns = Decimal(seconds) * Decimal("1000000000")
    if not ns.is_finite() or ns != ns.to_integral_value():
        raise ValueError("Published decimal cannot be represented in integer ns")
    return int(ns)


def to_day(day: str) -> int:
    d = Decimal(day)
    if not d.is_finite() or d != d.to_integral_value():
        raise ValueError("Expected integral MJD for fixed-point Lean theorem")
    return int(d)


def generate(record: dict) -> str:
    p17.check(record)  # full lineage, time-scale and no-528-activation lock
    model = record["model"]
    lo, hi = model["branches"]
    origin = to_day(model["mjd_reference"])
    cut = to_day(model["boundary_mjd"])
    if to_day(lo["end_mjd_exclusive"]) != cut or to_day(hi["start_mjd"]) != cut:
        raise ValueError("Clock cutoff is not shared by both branches")
    lower, upper = to_ns(lo["intercept_seconds"]), to_ns(hi["intercept_seconds"])
    jump = to_ns(model["intercept_difference_seconds"])
    rate = to_ns(model["slope_seconds_per_day"])
    if upper - lower != jump or jump <= 0:
        raise ValueError("Inconsistent source-locked discontinuity")
    nov8 = to_ns(str(p17.a1_minus_wwv("38341.0")))
    return TEMPLATE.substitute(lower=lower, upper=upper, rate=rate,
                               origin=origin, cut=cut, jump=jump, nov8=nov8)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--ledger", type=Path, default=p17.LEDGER)
    args = ap.parse_args()
    generated = generate(json.loads(args.ledger.read_text(encoding="utf-8")))
    if args.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != generated:
            raise SystemExit("STALE Lean SAO P-17 clock certificate")
        print("PASS exact SAO P-17 source-to-Lean certificate")
    else:
        OUT.write_text(generated, encoding="utf-8")
        print(OUT)


if __name__ == "__main__":
    main()
